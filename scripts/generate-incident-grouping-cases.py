def records(split: str, groups: dict[str, list[str]]) -> list[dict[str, str]]:
    start = datetime(2026, 9, 1, tzinfo=timezone.utc)
    result = []
    index = 0
    for label, descriptions in groups.items():
        if len(descriptions) != 10:
            raise ValueError(f"{split}/{label} must contain exactly 10 curated descriptions")
        for description in descriptions:
            index += 1
            result.append({
                "id": f"{split[:1].upper()}-{index:03}",
                "split": split,
                "eventLabel": label,
                "merchant": "merchant-demo",
                "businessType": "PAY",
                "phase": "PAYMENT_QUERY",
                "channel": "simulated-channel",
                "abnormalType": "QUERY_ERROR",
                "errorCode": "CHANNEL_QUERY_ERROR",
                "occurredAt": (start + timedelta(seconds=index)).isoformat(),
                "description": description,
            })
    return result


def main() -> None:
    if set(DEV) != set(HOLDOUT):
        raise ValueError("development and holdout labels must match")
    output = Path(__file__).resolve().parents[1] / "docs" / "paylens" / "grouping-evaluation"
    output.mkdir(parents=True, exist_ok=True)
    for split, groups in (("development", DEV), ("holdout", HOLDOUT)):
        cases = records(split, groups)
        target = output / f"{split}.json"
        target.write_text(json.dumps(cases, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"{target}: {len(cases)} curated synthetic observations")


if __name__ == "__main__":
    main()
